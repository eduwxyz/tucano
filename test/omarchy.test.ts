import { mkdirSync, mkdtempSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { tmpdir } from 'node:os'
import { afterEach, expect, it } from 'vitest'
import { contrast, hexColor, omarchyPalette, parseColorsToml } from '../src/shared/omarchy'
import { readOmarchy, watchOmarchy } from '../src/main/omarchy'
import { Workspaces } from '../src/main/workspaces'

// Three of the themes Omarchy ships, as their colors.toml: one dark, two light.
const fixture = (name: string): string => readFileSync(join(import.meta.dirname, 'fixtures', 'omarchy', `${name}.toml`), 'utf8')
const linux = process.platform === 'linux'

const dirs: string[] = []
const temp = (): string => { const dir = mkdtempSync(join(tmpdir(), 'tucano-omarchy-')); dirs.push(dir); return dir }
afterEach(() => { for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true }) })

it('reads the flat colors.toml, quoted or not, with comments around it', () => {
  expect(parseColorsToml('# Generated by Aether\nmode = "dark"\naccent = "#7aa2f7" # blue\ncolor1 = 0xf7768e\n\nbad line\n')).toEqual({ mode: 'dark', accent: '#7aa2f7', color1: '0xf7768e' })
  expect(hexColor('#ABC')).toBe('#aabbcc')
  expect(hexColor('0x1A1B26')).toBe('#1a1b26')
  expect(hexColor('rgb(1,2,3)')).toBeUndefined()
  expect(hexColor(undefined)).toBeUndefined()
})

it('maps a dark theme onto the tokens, with the canvas a step under the panels', () => {
  const p = omarchyPalette(fixture('tokyo-night'))!
  expect(p.mode).toBe('dark')
  expect(p.vars['--panel']).toBe('#1a1b26')
  expect(p.vars['--bg']).toBe('#13141c') // dark_background
  expect(p.background).toBe(p.vars['--bg'])
  expect(p.vars['--text']).toBe('#a9b1d6')
  expect(p.vars['--accent']).toBe('#7aa2f7')
  expect(p.vars['--danger']).toBe('#f7768e')
  expect(p.vars['--select-caret']).toContain(`stroke='%23${p.vars['--text-3']!.slice(1)}'`)
})

it('keeps a light theme light, and its text and buttons readable', () => {
  for (const name of ['white', 'catppuccin-latte', 'tokyo-night']) {
    const p = omarchyPalette(fixture(name))!
    expect(p.mode).toBe(name === 'tokyo-night' ? 'dark' : 'light')
    expect(contrast(p.vars['--text']!, p.vars['--panel']!), name).toBeGreaterThanOrEqual(4.5)
    expect(contrast(p.vars['--text-2']!, p.vars['--panel']!), name).toBeGreaterThanOrEqual(4.5)
    for (const token of ['--text-3', '--accent', '--ok', '--warn', '--danger'] as const) expect(contrast(p.vars[token]!, p.vars['--panel']!), `${name} ${token}`).toBeGreaterThanOrEqual(3)
    expect(contrast(p.vars['--primary-text']!, p.vars['--primary']!), name).toBeGreaterThanOrEqual(4.5)
    expect(contrast(p.vars['--accent-text']!, p.vars['--accent']!), name).toBeGreaterThanOrEqual(4.5)
  }
})

it('builds a theme converted from alacritty, which has only color0–15 and no mode', () => {
  const palette = Array.from({ length: 16 }, (_, i) => `color${i} = "0x${['111c18', 'ff5345', '549e6a', 'e5c736', '509475', 'd2689c', '2dd5b7', 'f6f5dd'][i % 8]}"`).join('\n')
  const p = omarchyPalette(`accent = "#509475"\nselection = "#f6f5dd"\n${palette}`)!
  expect(p.mode).toBe('dark') // from the background being darker than the text
  expect(p.vars['--panel']).toBe('#111c18')
  expect(p.vars['--text']).toBe('#f6f5dd')
  expect(p.vars['--ok']).toBe('#549e6a')
  // No accent at all: the theme's blue, then its text.
  expect(omarchyPalette('background = "#ffffff"\nforeground = "#000000"\nblue = "#0000ff"')!.vars['--accent']).toBe('#0000ff')
  expect(omarchyPalette('background = "#ffffff"\nforeground = "#000000"')!.mode).toBe('light')
})

it('gives nothing for a file without a background and a foreground', () => {
  expect(omarchyPalette('accent = "#7aa2f7"')).toBeNull()
  expect(omarchyPalette('')).toBeNull()
})

it.runIf(linux)("reads the desktop's current theme, from the state folder or the older config one", () => {
  const home = temp()
  const state = join(home, 'state')
  const config = join(home, 'config')
  expect(readOmarchy([state, config])).toBeNull()
  mkdirSync(join(config, 'theme'), { recursive: true })
  writeFileSync(join(config, 'theme', 'colors.toml'), fixture('white'))
  expect(readOmarchy([state, config])?.palette?.mode).toBe('light')
  mkdirSync(join(state, 'theme'), { recursive: true })
  writeFileSync(join(state, 'theme', 'colors.toml'), fixture('tokyo-night'))
  writeFileSync(join(state, 'theme.name'), 'tokyo-night\n')
  expect(readOmarchy([state, config])).toMatchObject({ name: 'tokyo-night', palette: { mode: 'dark' } })
})

it.runIf(linux)('still says it is Omarchy under a theme with no colours, so the choice can be turned off', () => {
  // Osaka Jade ships no colors.toml: the window keeps Tucano's colours, the choice stays.
  const current = join(temp(), 'current')
  mkdirSync(join(current, 'theme'), { recursive: true })
  writeFileSync(join(current, 'theme.name'), 'osaka-jade\n')
  expect(readOmarchy([current])).toEqual({ name: 'osaka-jade', palette: null })
  writeFileSync(join(current, 'theme', 'colors.toml'), 'accent = "#7aa2f7"\n') // nothing to build on
  expect(readOmarchy([current])).toEqual({ name: 'osaka-jade', palette: null })
})

it.runIf(linux)('sees a switch, which renames the next theme over the current one', async () => {
  const current = join(temp(), 'current')
  mkdirSync(join(current, 'theme'), { recursive: true })
  writeFileSync(join(current, 'theme', 'colors.toml'), fixture('tokyo-night'))
  const seen: (string | undefined)[] = []
  const stop = watchOmarchy((t) => seen.push(t?.palette?.mode ?? (t ? 'none' : undefined)), [current])
  try {
    // What omarchy-theme-set does: build next-theme/, then move it over theme/.
    mkdirSync(join(current, 'next-theme'))
    writeFileSync(join(current, 'next-theme', 'colors.toml'), fixture('white'))
    rmSync(join(current, 'theme'), { recursive: true })
    renameSync(join(current, 'next-theme'), join(current, 'theme'))
    await expect.poll(() => seen, { timeout: 3_000 }).toEqual(['light'])
    // …and a file rewritten in place, inside the new folder.
    writeFileSync(join(current, 'theme', 'colors.toml'), fixture('tokyo-night'))
    await expect.poll(() => seen, { timeout: 3_000 }).toEqual(['light', 'dark'])
    // …and a switch to a theme with no colours is still a change, not Omarchy going away.
    rmSync(join(current, 'theme'), { recursive: true })
    mkdirSync(join(current, 'theme'))
    await expect.poll(() => seen, { timeout: 3_000 }).toEqual(['light', 'dark', 'none'])
  } finally {
    stop()
  }
})

it('keeps following Omarchy as this computer’s choice, across restarts', () => {
  const dir = temp()
  const registry = new Workspaces(dir)
  expect(registry.omarchy()).toBe(false)
  registry.setOmarchy(true)
  expect(new Workspaces(dir).omarchy()).toBe(true)
  registry.setOmarchy(false)
  expect(new Workspaces(dir).omarchy()).toBe(false)
  const file = join(dir, 'workspaces.json')
  writeFileSync(file, JSON.stringify({ ...JSON.parse(readFileSync(file, 'utf8')), omarchy: 'yes' }))
  expect(() => new Workspaces(dir)).toThrow()
})
